const horaRecife = new Intl.DateTimeFormat('pt-BR', {
  timeZone: 'America/Recife',
  hour: 'numeric',
  hourCycle: 'h23',
});

export function periodoEmRecife(agora = new Date()) {
  const hora = Number(horaRecife.format(agora));
  if (hora >= 5 && hora < 12) return 'manha';
  if (hora >= 12 && hora < 18) return 'tarde';
  return 'noite';
}

export function escolherMensagem(mensagens: readonly string[], anterior: string | null) {
  const indiceAnterior = mensagens.indexOf(anterior ?? '');
  const indice = Math.floor(Math.random() * (mensagens.length - Number(indiceAnterior >= 0)));
  return mensagens[indice >= indiceAnterior && indiceAnterior >= 0 ? indice + 1 : indice];
}
